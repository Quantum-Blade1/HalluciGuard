def validate_schema(record: dict, schema: dict) -> ValidationResult:
    result = ValidationResult(is_valid=True)
    for field_name, field_spec in schema.items():
        if field_spec.get("required") and field_name not in record:
            result.add_error(f"Missing required field: {field_name}")
            continue
        if field_name in record:
            value = record[field_name]
            expected_type = field_spec.get("type")
            if expected_type and not isinstance(value, expected_type):
                result.add_error(f"Field {field_name}: expected {expected_type.__name__}, got {type(value).__name__}")
            min_val = field_spec.get("min")
            max_val = field_spec.get("max")
            if min_val is not None and value < min_val:
                result.add_error(f"Field {field_name}: {value} < min {min_val}")
            if max_val is not None and value > max_val:
                result.add_error(f"Field {field_name}: {value} > max {max_val}")
            pattern = field_spec.get("pattern")
            if pattern and isinstance(value, str):
                if not re.match(pattern, value):
                    result.add_error(f"Field {field_name}: does not match pattern {pattern}")
    result.score = 1.0 - (len(result.errors) / max(len(schema), 1))
    return result


