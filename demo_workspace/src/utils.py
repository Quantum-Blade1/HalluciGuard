def retry(fn, retries: int = MAX_RETRIES, exceptions: tuple = (Exception,)):
    last_exc = None
    for attempt in range(retries):
        try:
            return fn()
        except exceptions as e:
            last_exc = e
            logger.warning("Attempt %d/%d failed: %s", attempt + 1, retries, e)
    raise last_exc


