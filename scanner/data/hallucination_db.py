"""
Hallucination Database.

Maintains a list of known hallucinated package names generated by LLMs,
plus pattern-based detection for suspicious naming conventions.

Default data path: Path(__file__).parent.parent.parent / "data" / "hallucination_db"
This resolves to <extension_root>/data/hallucination_db/ when the scanner is
bundled inside the VS Code extension at <extension_root>/scanner/.
"""

from __future__ import annotations

import json
import logging
from pathlib import Path

logger = logging.getLogger(__name__)

# Default hallucination DB dir: scanner/data/hallucination_db.py -> scanner/data/ -> scanner/ -> project root -> data/hallucination_db/
_DEFAULT_HALLUCINATION_DB_DIR = Path(__file__).resolve().parent.parent.parent / "data" / "hallucination_db"

# Suspicious suffixes commonly seen in AI-hallucinated package names
SUSPICIOUS_SUFFIXES = [
    "-helper", "-helpers", "-utils", "-util", "-lib", "-tool", "-tools",
    "-client", "-sdk", "-api", "-core", "-base", "-common", "-extra",
    "-plus", "-pro", "-advanced", "-secure", "-fast", "-easy", "-simple",
    "-modern", "-new", "-next", "-enhanced",
]

# Suspicious prefixes
SUSPICIOUS_PREFIXES = [
    "py-", "python-", "node-", "js-", "secure-", "fast-", "easy-",
    "simple-", "modern-", "smart-", "auto-", "super-", "mega-",
]


class HallucinationDB:
    """Database of known hallucinated package names."""

    def __init__(self, db_dir: Path | None = None) -> None:
        self._db_dir = db_dir or _DEFAULT_HALLUCINATION_DB_DIR
        self._known: set[str] = set()
        self._loaded = False

    def _ensure_loaded(self) -> None:
        if self._loaded:
            return
        path = self._db_dir / "known_hallucinations.json"
        if path.exists():
            try:
                with open(path, "r") as f:
                    data = json.load(f)
                if isinstance(data, list):
                    self._known = {name.lower() for name in data if isinstance(name, str)}
                    logger.info("Loaded %d known hallucinated packages from %s", len(self._known), path)
            except (json.JSONDecodeError, OSError) as e:
                logger.error("Failed to load hallucination DB from %s: %s", path, e)
        else:
            logger.warning("Hallucination DB not found at %s", path)
        self._loaded = True

    def is_hallucinated(self, package_name: str) -> bool:
        """Check if a package name is a known hallucination."""
        self._ensure_loaded()
        return package_name.lower() in self._known

    def matches_suspicious_pattern(self, package_name: str) -> bool:
        """Check if the name matches patterns typical of hallucinated packages."""
        name = package_name.lower()
        for suffix in SUSPICIOUS_SUFFIXES:
            if name.endswith(suffix):
                stem = name[: -len(suffix)]
                if len(stem) >= 3:
                    return True
        for prefix in SUSPICIOUS_PREFIXES:
            if name.startswith(prefix):
                remainder = name[len(prefix):]
                if len(remainder) >= 3:
                    return True
        # Compound names with many hyphens
        if name.count("-") >= 3:
            return True
        return False

    def add_hallucination(self, package_name: str) -> None:
        """Add a name to the known hallucinations set."""
        self._ensure_loaded()
        self._known.add(package_name.lower())

    @property
    def count(self) -> int:
        self._ensure_loaded()
        return len(self._known)
